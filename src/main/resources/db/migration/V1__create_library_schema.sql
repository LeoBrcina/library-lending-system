
-- V1: Initial database schema for the P03 Library Lending System
--
-- PostgreSQL 17
-- Based on the M1 ER diagram and ADR-001.
--
-- PostgreSQL folds unquoted identifiers to lowercase.
-- PascalCase logical names are retained here for readability.
-- JPA mappings must reference the corresponding physical names.
--
-- Business rules involving multiple records are implemented later
-- in transactional services, with database constraints where possible.

-- ============================================================
-- 1. CATALOG
-- ============================================================

CREATE TABLE BookTitles (
                            Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            ISBN VARCHAR(20),
                            Title VARCHAR(255) NOT NULL,
                            Authors VARCHAR(500) NOT NULL,
                            Publisher VARCHAR(255),
                            PublicationYear INTEGER,
                            Description TEXT,
                            Active BOOLEAN NOT NULL DEFAULT TRUE,
                            CreatedAt TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            UpdatedAt TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                            CONSTRAINT ck_booktitles_title
                                CHECK (LENGTH(TRIM(Title)) > 0),

                            CONSTRAINT ck_booktitles_authors
                                CHECK (LENGTH(TRIM(Authors)) > 0),

                            CONSTRAINT ck_booktitles_publication_year
                                CHECK (PublicationYear IS NULL OR
                                       PublicationYear BETWEEN 1450 AND 2200)
);

CREATE INDEX idx_booktitles_title
    ON BookTitles (Title);

CREATE TABLE Categories (
                            Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            Code VARCHAR(50) NOT NULL,
                            Name VARCHAR(150) NOT NULL,

                            CONSTRAINT uq_categories_code UNIQUE (Code),

                            CONSTRAINT ck_categories_code
                                CHECK (LENGTH(TRIM(Code)) > 0),

                            CONSTRAINT ck_categories_name
                                CHECK (LENGTH(TRIM(Name)) > 0)
);

CREATE TABLE BookCategories (
                                BookTitleId BIGINT NOT NULL,
                                CategoryId BIGINT NOT NULL,
                                IsPrimary BOOLEAN NOT NULL DEFAULT FALSE,

                                CONSTRAINT pk_bookcategories
                                    PRIMARY KEY (BookTitleId, CategoryId),

                                CONSTRAINT fk_bookcategories_title
                                    FOREIGN KEY (BookTitleId)
                                        REFERENCES BookTitles (Id)
                                        ON DELETE CASCADE,

                                CONSTRAINT fk_bookcategories_category
                                    FOREIGN KEY (CategoryId)
                                        REFERENCES Categories (Id)
                                        ON DELETE RESTRICT
);

-- At most one primary category per book title.
CREATE UNIQUE INDEX uq_bookcategories_one_primary
    ON BookCategories (BookTitleId)
    WHERE IsPrimary = TRUE;

CREATE INDEX idx_bookcategories_category
    ON BookCategories (CategoryId);

CREATE TABLE BookCopies (
                            Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            BookTitleId BIGINT NOT NULL,
                            InventoryCode VARCHAR(100) NOT NULL,
                            CopyCondition VARCHAR(30) NOT NULL,
                            Status VARCHAR(30) NOT NULL,
                            AcquiredAt DATE,

                            CONSTRAINT uq_bookcopies_inventory_code
                                UNIQUE (InventoryCode),

                            CONSTRAINT fk_bookcopies_title
                                FOREIGN KEY (BookTitleId)
                                    REFERENCES BookTitles (Id)
                                    ON DELETE RESTRICT,

                            CONSTRAINT ck_bookcopies_inventory_code
                                CHECK (LENGTH(TRIM(InventoryCode)) > 0),

                            CONSTRAINT ck_bookcopies_condition
                                CHECK (LENGTH(TRIM(CopyCondition)) > 0),

                            CONSTRAINT ck_bookcopies_status
                                CHECK (LENGTH(TRIM(Status)) > 0)
);

CREATE INDEX idx_bookcopies_title
    ON BookCopies (BookTitleId);

CREATE INDEX idx_bookcopies_title_status
    ON BookCopies (BookTitleId, Status);


-- ============================================================
-- 2. USERS AND ROLES
-- ============================================================

CREATE TABLE AppUsers (
                          Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          Email VARCHAR(255) NOT NULL,
                          PasswordHash VARCHAR(255) NOT NULL,
                          FirstName VARCHAR(100) NOT NULL,
                          LastName VARCHAR(100) NOT NULL,
                          Enabled BOOLEAN NOT NULL DEFAULT TRUE,
                          CreatedAt TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT ck_appusers_email
                              CHECK (LENGTH(TRIM(Email)) > 0),

                          CONSTRAINT ck_appusers_password
                              CHECK (LENGTH(TRIM(PasswordHash)) > 0),

                          CONSTRAINT ck_appusers_first_name
                              CHECK (LENGTH(TRIM(FirstName)) > 0),

                          CONSTRAINT ck_appusers_last_name
                              CHECK (LENGTH(TRIM(LastName)) > 0)
);

-- Email uniqueness must not depend on letter case.
CREATE UNIQUE INDEX uq_appusers_email_lower
    ON AppUsers (LOWER(Email));

CREATE TABLE Roles (
                       Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       Name VARCHAR(30) NOT NULL,

                       CONSTRAINT uq_roles_name UNIQUE (Name),

                       CONSTRAINT ck_roles_name
                           CHECK (LENGTH(TRIM(Name)) > 0)
);

CREATE TABLE UserRoles (
                           UserId BIGINT NOT NULL,
                           RoleId BIGINT NOT NULL,

                           CONSTRAINT pk_userroles
                               PRIMARY KEY (UserId, RoleId),

                           CONSTRAINT fk_userroles_user
                               FOREIGN KEY (UserId)
                                   REFERENCES AppUsers (Id)
                                   ON DELETE CASCADE,

                           CONSTRAINT fk_userroles_role
                               FOREIGN KEY (RoleId)
                                   REFERENCES Roles (Id)
                                   ON DELETE RESTRICT
);

CREATE INDEX idx_userroles_role
    ON UserRoles (RoleId);


-- ============================================================
-- 3. RESERVATIONS
-- ============================================================

-- Reservations are created at title level.
-- AllocatedCopyId is null while no physical copy is assigned.

CREATE TABLE Reservations (
                              Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              BookTitleId BIGINT NOT NULL,
                              MemberId BIGINT NOT NULL,
                              AllocatedCopyId BIGINT,
                              Status VARCHAR(30) NOT NULL,
                              RequestedAt TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              ReadyAt TIMESTAMPTZ,
                              PickupDeadline TIMESTAMPTZ,
                              FulfilledAt TIMESTAMPTZ,

                              CONSTRAINT fk_reservations_title
                                  FOREIGN KEY (BookTitleId)
                                      REFERENCES BookTitles (Id)
                                      ON DELETE RESTRICT,

                              CONSTRAINT fk_reservations_member
                                  FOREIGN KEY (MemberId)
                                      REFERENCES AppUsers (Id)
                                      ON DELETE RESTRICT,

                              CONSTRAINT fk_reservations_copy
                                  FOREIGN KEY (AllocatedCopyId)
                                      REFERENCES BookCopies (Id)
                                      ON DELETE RESTRICT,

                              CONSTRAINT ck_reservations_status
                                  CHECK (LENGTH(TRIM(Status)) > 0),

                              CONSTRAINT ck_reservations_pickup_deadline
                                  CHECK (PickupDeadline IS NULL OR
                                         ReadyAt IS NOT NULL),

                              CONSTRAINT ck_reservations_pickup_order
                                  CHECK (PickupDeadline IS NULL OR
                                         PickupDeadline > ReadyAt)
);

-- Supports deterministic FIFO ordering.
CREATE INDEX idx_reservations_queue
    ON Reservations (BookTitleId, Status, RequestedAt, Id);

CREATE INDEX idx_reservations_member
    ON Reservations (MemberId);

CREATE INDEX idx_reservations_allocated_copy
    ON Reservations (AllocatedCopyId);

CREATE INDEX idx_reservations_pickup_deadline
    ON Reservations (Status, PickupDeadline);


-- ============================================================
-- 4. LOANS AND FINES
-- ============================================================

CREATE TABLE Loans (
                       Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       BookCopyId BIGINT NOT NULL,
                       MemberId BIGINT NOT NULL,
                       IssuedById BIGINT NOT NULL,
                       ReturnedById BIGINT,
                       ReservationId BIGINT,
                       CheckedOutAt TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       DueDate DATE NOT NULL,
                       ReturnedAt TIMESTAMPTZ,
                       RenewalCount INTEGER NOT NULL DEFAULT 0,
                       Version BIGINT NOT NULL DEFAULT 0,

                       CONSTRAINT fk_loans_copy
                           FOREIGN KEY (BookCopyId)
                               REFERENCES BookCopies (Id)
                               ON DELETE RESTRICT,

                       CONSTRAINT fk_loans_member
                           FOREIGN KEY (MemberId)
                               REFERENCES AppUsers (Id)
                               ON DELETE RESTRICT,

                       CONSTRAINT fk_loans_issued_by
                           FOREIGN KEY (IssuedById)
                               REFERENCES AppUsers (Id)
                               ON DELETE RESTRICT,

                       CONSTRAINT fk_loans_returned_by
                           FOREIGN KEY (ReturnedById)
                               REFERENCES AppUsers (Id)
                               ON DELETE RESTRICT,

                       CONSTRAINT fk_loans_reservation
                           FOREIGN KEY (ReservationId)
                               REFERENCES Reservations (Id)
                               ON DELETE RESTRICT,

                       CONSTRAINT uq_loans_reservation
                           UNIQUE (ReservationId),

                       CONSTRAINT ck_loans_renewal_count
                           CHECK (RenewalCount BETWEEN 0 AND 2),

                       CONSTRAINT ck_loans_version
                           CHECK (Version >= 0),

                       CONSTRAINT ck_loans_return_order
                           CHECK (ReturnedAt IS NULL OR
                                  ReturnedAt >= CheckedOutAt)
);

-- A physical copy cannot have two simultaneous active loans.
CREATE UNIQUE INDEX uq_loans_one_active_per_copy
    ON Loans (BookCopyId)
    WHERE ReturnedAt IS NULL;

CREATE INDEX idx_loans_member
    ON Loans (MemberId);

CREATE INDEX idx_loans_member_active
    ON Loans (MemberId)
    WHERE ReturnedAt IS NULL;

CREATE INDEX idx_loans_active_due_date
    ON Loans (DueDate)
    WHERE ReturnedAt IS NULL;

CREATE INDEX idx_loans_issued_by
    ON Loans (IssuedById);

CREATE INDEX idx_loans_returned_by
    ON Loans (ReturnedById);

CREATE TABLE FineAccruals (
                              Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              LoanId BIGINT NOT NULL,
                              AccrualDate DATE NOT NULL,
                              Amount NUMERIC(10, 2) NOT NULL,

                              CONSTRAINT fk_fineaccruals_loan
                                  FOREIGN KEY (LoanId)
                                      REFERENCES Loans (Id)
                                      ON DELETE RESTRICT,

                              CONSTRAINT uq_fineaccruals_loan_date
                                  UNIQUE (LoanId, AccrualDate),

                              CONSTRAINT ck_fineaccruals_amount
                                  CHECK (Amount > 0)
);

-- LoanId + AccrualDate is already indexed by the unique constraint.


-- ============================================================
-- 5. PURCHASE SUGGESTIONS AND AI RESULTS
-- ============================================================

CREATE TABLE PurchaseSuggestions (
                                     Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     MemberId BIGINT NOT NULL,
                                     ReviewedById BIGINT,
                                     SuggestedTitle VARCHAR(255) NOT NULL,
                                     Description TEXT NOT NULL,
                                     Status VARCHAR(30) NOT NULL,
                                     SubmittedAt TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                     ReviewedAt TIMESTAMPTZ,

                                     CONSTRAINT fk_purchasesuggestions_member
                                         FOREIGN KEY (MemberId)
                                             REFERENCES AppUsers (Id)
                                             ON DELETE RESTRICT,

                                     CONSTRAINT fk_purchasesuggestions_reviewer
                                         FOREIGN KEY (ReviewedById)
                                             REFERENCES AppUsers (Id)
                                             ON DELETE RESTRICT,

                                     CONSTRAINT ck_purchasesuggestions_title
                                         CHECK (LENGTH(TRIM(SuggestedTitle)) > 0),

                                     CONSTRAINT ck_purchasesuggestions_status
                                         CHECK (LENGTH(TRIM(Status)) > 0),

                                     CONSTRAINT ck_purchasesuggestions_reviewed_at
                                         CHECK (ReviewedAt IS NULL OR
                                                ReviewedById IS NOT NULL)
);

CREATE INDEX idx_purchasesuggestions_member
    ON PurchaseSuggestions (MemberId);

CREATE INDEX idx_purchasesuggestions_status
    ON PurchaseSuggestions (Status, SubmittedAt);

CREATE INDEX idx_purchasesuggestions_reviewer
    ON PurchaseSuggestions (ReviewedById);

CREATE TABLE AiSuggestionResults (
                                     Id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     PurchaseSuggestionId BIGINT NOT NULL,
                                     SuggestedCategories JSONB,
                                     DuplicateCandidates JSONB,
                                     ProcessingStatus VARCHAR(30) NOT NULL,
                                     CreatedAt TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                     CONSTRAINT fk_aisuggestionresults_suggestion
                                         FOREIGN KEY (PurchaseSuggestionId)
                                             REFERENCES PurchaseSuggestions (Id)
                                             ON DELETE RESTRICT,

                                     CONSTRAINT ck_aisuggestionresults_status
                                         CHECK (LENGTH(TRIM(ProcessingStatus)) > 0)
);

CREATE INDEX idx_aisuggestionresults_suggestion
    ON AiSuggestionResults (PurchaseSuggestionId, CreatedAt);
